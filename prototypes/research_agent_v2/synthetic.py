"""Closed generated inputs, with replayable canonical evidence; never user file IO."""

import json
from hashlib import sha256

from docs.canonical_assessment.model import Scale
from prototypes.adaptive_assessment.adapters import ItemSpec, _assemble
from prototypes.adaptive_assessment.data import Envelope, PrototypeError

from .review_sources import RECIPES as REVIEW_RECIPES
from .review_sources import specification as review_specification

# Evaluation inputs are separate fixed seeds; no planner sees these names or seeds.
RECIPES = {
    "research-v2-capability": (48, 4, "competency", 701),
    "research-v2-questions": (40, 7, "question", 702),
    "research-v2-holdout-interaction": (72, 6, "competency", 1907),
    "research-v2-holdout-relation": (56, 9, "question", 1913),
    "research-v2-holdout-empty": (32, 3, "competency", 1919),
    "research-v2-final-interaction": (64, 8, "competency", 9001),
    "research-v2-final-relation": (80, 11, "question", 9007),
    "research-v2-final-empty": (36, 4, "competency", 9011),
}

RECIPES.update({name: None for name in REVIEW_RECIPES})


def specification(recipe: str) -> dict:
    if recipe in REVIEW_RECIPES:
        return review_specification(recipe)
    try:
        n, count, kind, seed = RECIPES[recipe]
    except KeyError:
        raise PrototypeError("unregistered_research_source") from None
    lo, hi = (1, 5) if kind == "competency" else (20, 80)
    rows = []
    for i in range(n):
        a, b = (i + seed) & 1, ((i // 2) + seed // 2) & 1
        if recipe.endswith("empty"):
            row = [3] * count
        elif kind == "competency":
            row = [lo if not a else hi, lo if not b else hi, lo if a == b else hi] + [3] * (
                count - 3
            )
        else:
            row = [lo if not a else hi, hi if not a else lo]
            row += [lo if ((i >> (j % 3)) & 1) == 0 else hi for j in range(2, count)]
            if recipe == "research-v2-questions" and i >= n - 10:
                row[-1] = None
        rows.append(row)
    return {
        "protocol": "research-synthetic-v2",
        "kind": kind,
        "rows": rows,
        "minimum": "1" if kind == "competency" else "0",
        "maximum": "5" if kind == "competency" else "100",
        "step": "0.01",
    }


def raw_source(recipe: str) -> bytes:
    return json.dumps(specification(recipe), sort_keys=True, separators=(",", ":")).encode()


def decode_registered(raw: bytes):
    # Exact regenerated bytes, not an arbitrary JSON parsing/import endpoint.
    recipe = next((r for r in RECIPES if raw_source(r) == raw), None)
    if recipe is None:
        raise PrototypeError("unregistered_research_bytes")
    spec = specification(recipe)
    prefix = "I" if spec["kind"] == "competency" else "Q"
    count = len(spec["rows"][0])
    ids = spec.get("item_ids", [f"{prefix}{i + 1:02}" for i in range(count)])
    unit = "level" if prefix == "I" else "points"
    items = [
        ItemSpec(
            item,
            f"合成评价项 {item}",
            spec["kind"],
            Scale("scale-" + item, spec["minimum"], spec["maximum"], spec["step"], unit),
            spec.get("measurement_level", "ordinal" if prefix == "I" else "interval"),
            "",
            None,
        )
        for item in ids
    ]
    rows = []
    for i, scores in enumerate(spec["rows"]):
        pid = f"S{i:04}"
        rows.append(
            (
                pid,
                [
                    (
                        item,
                        None if v is None else str(v),
                        "",
                        f"synthetic.json#rows/{i}/{j}",
                        "available",
                    )
                    for j, (item, v) in enumerate(zip(ids, scores, strict=True))
                ],
                "synthetic.json",
            )
        )
    return _assemble(raw, items, rows, "research", {"synthetic.json": sha256(raw).hexdigest()})


class ResearchEnvelope(Envelope):
    def validate(self) -> None:
        self.data.validate()
        if decode_registered(self.source_bytes) != self.material:
            raise PrototypeError("source_binding_mismatch")


def materialize(recipe: str) -> Envelope:
    raw = raw_source(recipe)
    return ResearchEnvelope(decode_registered(raw), raw, "research-v2")
